#ifndef STATUS_H
#define STATUS_H

typedef enum {
    STATUS_OK = 0,
    STATUS_INPUT_END,
    STATUS_MATCH_FAILURE,
    STATUS_ERR_NULL_ARGUMENT,
    STATUS_ERR_FORMAT_INVALID,
    STATUS_ERR_FORMAT_UNSUPPORTED,
    STATUS_ERR_SPEC_TOO_LONG,
    STATUS_ERR_POINTER_ARGUMENT_NULL,
    STATUS_ERR_BASE_OUT_OF_RANGE,
    STATUS_ERR_INPUT_TOO_LONG,
    STATUS_ERR_READ_FAILED
} Status;

const char *status_message(const Status status);

#endif
